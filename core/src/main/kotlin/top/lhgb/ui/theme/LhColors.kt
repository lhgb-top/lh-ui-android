/**
 * 主题色板：把 core 的 Color 令牌（明/暗两个并列对象）拍平成一层平展的 [Color] 集合，
 * 供组件直接消费。字段命名与 `LhTokens.Color.*` 一一对应（default 后缀去掉）。
 *
 * - 明色板 [LightLhColors] 取自 [LhTokens]；
 * - 暗色板 [DarkLhColors] 取自 [LhDarkTokens]（并列对象模型：暗色只覆盖 Color，不含尺寸）。
 *
 * 之所以做这层「拍平」，是因为 Kotlin 的 `object` 嵌套取值是 `LhTokens.Color.Primary.default`
 * 这样的链式路径；组件里写 `colors.primary` 更短，且明暗切换时组件代码完全不用改。
 */
data class LhColors(
  val primary: Color,
  val onPrimary: Color,
  val primaryHover: Color,
  val primaryActive: Color,
  val primaryBg: Color,
  val primaryBorder: Color,
  val selected: Color,
  val success: Color,
  val successHover: Color,
  val successActive: Color,
  val successBg: Color,
  val warning: Color,
  val warningHover: Color,
  val warningActive: Color,
  val warningBg: Color,
  val danger: Color,
  val dangerHover: Color,
  val dangerActive: Color,
  val dangerBg: Color,
  val info: Color,
  val infoHover: Color,
  val infoActive: Color,
  val infoBg: Color,
  val gold: Color,
  val goldHover: Color,
  val goldActive: Color,
  val goldBorder: Color,
  val jade: Color,
  val jadeHover: Color,
  val jadeActive: Color,
  val vermilion: Color,
  val vermilionHover: Color,
  val vermilionActive: Color,
  val textPrimary: Color,
  val textRegular: Color,
  val textSecondary: Color,
  val textPlaceholder: Color,
  val textDisabled: Color,
  val backgroundDefault: Color,
  val backgroundPage: Color,
  val backgroundOverlay: Color,
  val borderBase: Color,
  val borderLight: Color,
  val borderLighter: Color,
  val borderExtraLight: Color,
  val disabledBg: Color,
  val disabledText: Color,
  val disabledBorder: Color,
  val surface: Color,
  val ink: Color,
  val decoration: Color,
  val focus: Color,
  val hoverBg: Color,
)

